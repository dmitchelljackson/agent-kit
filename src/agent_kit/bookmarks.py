"""Bookmarks: skills generated from a page's `bookmark:` frontmatter.

The page is the source of truth. `.agents/skills/<name>/SKILL.md` is the
canonical generated copy; each configured agent gets a mirror in its own skills
folder (copies, not symlinks, so Windows works). akit only ever touches skill
files that carry its GENERATED marker.
"""

from __future__ import annotations

import re
import shutil
from dataclasses import dataclass
from pathlib import Path

from . import adapters
from . import frontmatter as fm
from .config import AkitError, Project
from .wiki import PAGE, Wiki

GENERATED = "<!-- akit:generated-bookmark -->"
CANONICAL = ".agents/skills"


@dataclass
class Bookmark:
    name: str
    when: str
    page: Path
    approval: str


def skill_name(wiki: Wiki, page_dir: Path) -> str:
    doc = fm.load(page_dir / PAGE)
    if doc.meta.get("bookmark_name"):
        return doc.meta["bookmark_name"]
    rel = wiki.rel(page_dir)
    name = re.sub(r"[^a-z0-9]+", "-", rel.lower()).strip("-") or "wiki"
    return name[:64].strip("-")


def list_bookmarks(wiki: Wiki) -> list[Bookmark]:
    out = []
    for d in wiki.page_dirs():
        doc = fm.load(d / PAGE)
        if doc.meta.get("bookmark"):
            out.append(Bookmark(skill_name(wiki, d), doc.meta["bookmark"], d, doc.meta.get("bookmark_approval", "")))
    return out


def render_skill(project: Project, wiki: Wiki, bm: Bookmark) -> str:
    page_rel = (bm.page.resolve().relative_to(project.root.resolve())).as_posix()
    desc = bm.when.rstrip(".") + ". The project wiki has pages you must read first."
    return fm.dump(
        {"name": bm.name, "description": desc},
        f"""{GENERATED}
<!-- Generated by akit from {page_rel}/{PAGE}. Edit that page's `bookmark` field, then run `akit bookmark sync`. -->

Before continuing, run this and read the whole output:

```bash
akit read {page_rel}
```

If something there conflicts with what you were about to do, follow the wiki.
If it seems wrong for this case, stop and ask the owner instead of working around it.

No `akit`? Read `{page_rel}/{PAGE}` and every atom it embeds (`![[name]]` is the file `name.md`).""",
    )


def skill_dirs(project: Project) -> list[Path]:
    rels = [CANONICAL]
    for a in project.agents:
        rel = adapters.get(a, project).get("skills_dir")
        if not rel:
            continue  # agent without skill support: AGENTS.md is its only channel
        if rel not in rels:
            rels.append(rel)
    return [project.root / r for r in rels]


def sync(project: Project, wiki: Wiki) -> list[str]:
    """Regenerate every bookmark skill; delete generated skills with no page behind them."""
    changes = []
    wanted = {bm.name: render_skill(project, wiki, bm) for bm in list_bookmarks(wiki)}
    for base in skill_dirs(project):
        if base.exists():
            for skill in base.glob("*/SKILL.md"):
                if GENERATED in skill.read_text(encoding="utf-8") and skill.parent.name not in wanted:
                    shutil.rmtree(skill.parent)
                    changes.append(f"removed {skill.parent.relative_to(project.root)}")
        for name, text in wanted.items():
            path = base / name / "SKILL.md"
            if path.exists():
                current = path.read_text(encoding="utf-8")
                if GENERATED not in current:
                    raise AkitError(f"{path.relative_to(project.root)} exists and wasn't generated by akit; rename the bookmark (bookmark_name).")
                if current == text:
                    continue
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            changes.append(f"wrote {path.relative_to(project.root)}")
    return changes


def stale(project: Project, wiki: Wiki) -> list[str]:
    problems = []
    wanted = {bm.name: render_skill(project, wiki, bm) for bm in list_bookmarks(wiki)}
    for base in skill_dirs(project):
        for name, text in wanted.items():
            p = base / name / "SKILL.md"
            if not p.exists() or p.read_text(encoding="utf-8") != text:
                problems.append(f"{p.relative_to(project.root)} is missing or stale; run `akit bookmark sync`")
        if base.exists():
            for skill in base.glob("*/SKILL.md"):
                if GENERATED in skill.read_text(encoding="utf-8") and skill.parent.name not in wanted:
                    problems.append(f"{skill.relative_to(project.root)} has no page behind it; run `akit bookmark sync`")
    return problems


def set_bookmark(wiki: Wiki, page_dir: Path, when: str, approval: str, name: str | None = None) -> None:
    when = when.strip()
    if not when.startswith("Use "):
        raise AkitError('A bookmark trigger must start with "Use " and name a moment, e.g. "Use before writing Kotlin unit tests".')
    doc = fm.load(page_dir / PAGE)
    doc.meta["bookmark"] = when
    doc.meta["bookmark_approval"] = approval
    if name:
        doc.meta["bookmark_name"] = name
    fm.save(doc)


def clear_bookmark(wiki: Wiki, page_dir: Path) -> None:
    doc = fm.load(page_dir / PAGE)
    for k in ("bookmark", "bookmark_approval", "bookmark_name"):
        doc.meta.pop(k, None)
    fm.save(doc)
